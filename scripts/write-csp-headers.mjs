// =============================================================================
// Write dist/_headers with the Content-Security-Policy for this deploy context
// =============================================================================
// Runs after `vite build`. Netlify can't vary headers in netlify.toml by
// deploy context, so the CSP lives here instead: production gets the strict
// policy; deploy previews additionally allow Netlify's review toolbar (the
// "Netlify Drawer"), which is an iframe from app.netlify.com. Everything
// else — HSTS, X-Frame-Options, etc. — stays in netlify.toml.
//
// Netlify sets CONTEXT to "production", "deploy-preview" or "branch-deploy".
// Any other value (CI, a laptop) gets the production policy.
// =============================================================================

import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const context = process.env.CONTEXT ?? 'production';
const isPreview = context === 'deploy-preview' || context === 'branch-deploy';

const directives = {
  'default-src': ["'self'"],
  'script-src': ["'self'", 'blob:', "'wasm-unsafe-eval'"],
  'worker-src': ["'self'", 'blob:'],
  'connect-src': ["'self'", 'https://*.supabase.co', 'wss://*.supabase.co', 'https://unpkg.com', 'https://*.sentry.io'],
  'img-src': ["'self'", 'data:', 'blob:', 'https://*.supabase.co'],
  'media-src': ["'self'", 'blob:', 'https://*.supabase.co'],
  'style-src': ["'self'", "'unsafe-inline'", 'https://fonts.googleapis.com'],
  'font-src': ["'self'", 'data:', 'https://fonts.gstatic.com'],
  'frame-src': ["'self'"],
  'object-src': ["'none'"],
  'frame-ancestors': ["'none'"],
  'base-uri': ["'self'"],
  'form-action': ["'self'"],
};

if (isPreview) {
  // Netlify Drawer (Deploy Preview Controls): review toolbar in an iframe.
  directives['frame-src'].push('https://app.netlify.com');
}

const csp = Object.entries(directives)
  .map(([k, v]) => `${k} ${v.join(' ')}`)
  .join('; ');

const out = `# Generated by scripts/write-csp-headers.mjs for CONTEXT=${context}. Do not edit.
/*
  Content-Security-Policy: ${csp}
`;

const dist = resolve(process.cwd(), 'dist');
mkdirSync(dist, { recursive: true });
writeFileSync(resolve(dist, '_headers'), out);
console.log(`[csp] wrote dist/_headers for ${context}${isPreview ? ' (Netlify Drawer allowed)' : ''}`);
